def test_r65_marker_column_path_unchanged_with_b3_in_place():
    """The R65/C-2 marker-column path must continue to work unchanged."""
    ap_df = pd.DataFrame([
        {"_adoptiq_provenance_row": True, "AdoptIQ_Status": "EMPTY", "STATUS_C": None},
    ])
    assert count_open_action_plans(None, ap_df) == 0


def test_r65_marker_column_with_real_rows_still_counts_correctly():
    """Marker column tags only the provenance row; real OPEN rows count."""
    ap_df = pd.DataFrame([
        {"_adoptiq_provenance_row": True, "AdoptIQ_Status": "EMPTY", "STATUS_C": None},
        {"_adoptiq_provenance_row": False, "AdoptIQ_Status": None, "STATUS_C": "Open"},
        {"_adoptiq_provenance_row": False, "AdoptIQ_Status": None, "STATUS_C": "Completed - Successful"},
    ])
    # Provenance skipped; 1 OPEN of the remaining 2.
    assert count_open_action_plans(None, ap_df) == 1
