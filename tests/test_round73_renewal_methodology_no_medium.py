def test_get_risk_scoring_explanation_carries_moderate_not_medium():
    """Render the methodology paragraph at runtime and verify the
    user-facing band label string is MODERATE."""

    from report_utils import get_risk_scoring_explanation  # noqa: PLC0415

    text = get_risk_scoring_explanation()
    # The methodology paragraph carries the parenthesised form
    # ``MODERATE (35-54)`` (or whatever the threshold values are).
    # We only check the band label token + opening paren; the actual
    # numbers depend on RISK_BAND_THRESHOLDS so are not pinned here.
    assert "MODERATE (" in text, (
        f"Round 73 / F9: methodology paragraph missing 'MODERATE (' "
        f"band label; got:\n{text}"
    )
    # The legacy MEDIUM rendering must be absent from the rendered string.
    # Note: we test for the SPECIFIC parenthesised form 'MEDIUM (' to
    # avoid false positives if a comment / explanation mentions MEDIUM
    # in a non-band-label context (currently none, but defensive).
    assert "MEDIUM (" not in text, (
        f"Round 73 / F9: methodology paragraph still carries 'MEDIUM (' "
        f"band label; got:\n{text}"
    )


def test_methodology_paragraph_carries_full_user_facing_band_set():
    """Sanity: the methodology paragraph carries CRITICAL / HIGH /
    MODERATE / LOW / HEALTHY (the full user-facing band set)."""

    from report_utils import get_risk_scoring_explanation  # noqa: PLC0415

    text = get_risk_scoring_explanation()
    for band in ("CRITICAL", "HIGH", "MODERATE", "LOW", "HEALTHY"):
        assert f"{band} (" in text or f"{band} (>" in text or f"{band} (<" in text, (
            f"Round 73 / F9: methodology paragraph missing {band!r} band "
            f"label; got:\n{text}"
        )


