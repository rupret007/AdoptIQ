"""Round 73 / Phase 3 (F9): no MEDIUM in the Risk Score Methodology paragraph.

Pre-Round 73 the ``Risk Score Methodology (0-100 scale)`` paragraph
generated by ``report_utils._render_risk_scoring_explanation`` rendered
the band labels ``CRITICAL / HIGH / MEDIUM / LOW / HEALTHY``.  This was
the SINGLE remaining user-facing surface in the Renewal Word doc still
emitting ``MEDIUM`` -- the R67 / B1 + B6 remap covered the
``Risk_Level`` column on Compact / Renewal XLSX, the R70 / Phase 3 #11
remap covered the Top-N Focus Accounts table cell paint, the Risk
Score box, the donut gauge, and the panel-2 of the 2x2 portfolio
chart.  The R70 vocabulary lint
(``test_round70_no_medium_in_user_facing.py``) explicitly whitelisted
the methodology paragraph (its docstring noted "1 of 9 hits is in the
deliberate Risk Score Methodology paragraph; that single instance is
fine").

Build 46 audit found this remaining ``MEDIUM`` was inconsistent with
the rest of the document and confused operators who saw "MODERATE"
everywhere ELSE in the report.  R73 / F9 closes the gap by remapping
the band string to ``MODERATE`` in the methodology paragraph render
itself.

The internal ``RISK_BAND_THRESHOLDS`` dict KEY stays ``MEDIUM`` for
cross-sheet parity (Comprehensive ``Risk_Components.risk_band`` agrees
byte-for-byte) and so internal filter / color lookups still resolve
correctly -- only the rendered user-facing string is remapped.

This file pins the F9 fix at three layers:

* The methodology paragraph contains ``MODERATE`` (not ``MEDIUM``).
* The ``RISK_BAND_THRESHOLDS`` dict KEY is unchanged (canonical
  band key contract preserved).
* The R73 / F9 source marker is in place so a future revert fails
  this assertion.
"""

from __future__ import annotations

from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent


def _read_report_utils_source() -> str:
    return (PROJECT_ROOT / "report_utils.py").read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# Source-shape pin
# ---------------------------------------------------------------------------


def test_source_marker_for_r73_f9_is_present():
    body = _read_report_utils_source()
    assert "Round 73 / Phase 3 (F9)" in body, (
        "Round 73 / F9: source marker missing -- the MODERATE remap in "
        "the methodology paragraph may have been reverted"
    )


def test_methodology_band_paragraph_uses_moderate_not_medium():
    """The rendered ``bands`` f-string MUST emit ``MODERATE (...)`` and
    MUST NOT emit ``MEDIUM (...)`` (the parenthesised form used in the
    rendered text)."""

    body = _read_report_utils_source()
    # The new MODERATE rendering must be present.
    assert 'f"MODERATE ({_fmt(med)}-{_fmt(high - 1)}), "' in body, (
        "Round 73 / F9: methodology paragraph must render MODERATE "
        "(not MEDIUM) for the rendered band label string"
    )
    # The pre-R73 MEDIUM rendering must be gone.
    assert 'f"MEDIUM ({_fmt(med)}-{_fmt(high - 1)}), "' not in body, (
        "Round 73 / F9: methodology paragraph still renders the legacy "
        "MEDIUM band label string -- the rename is incomplete"
    )


def test_risk_band_thresholds_dict_key_remains_medium():
    """R67 / B6 contract preserved: the canonical ``RISK_BAND_THRESHOLDS``
    dict KEY stays ``MEDIUM`` so cross-sheet parity (Comprehensive
    ``Risk_Components.risk_band``) and internal filter / color lookups
    still resolve correctly."""

    body = _read_report_utils_source()
    # The dict-key access pattern must still use MEDIUM (canonical key).
    assert '_BANDS.get("MEDIUM"' in body, (
        "Round 73 / F9: methodology renderer must still read the "
        "MEDIUM threshold from RISK_BAND_THRESHOLDS via the canonical "
        "key (R67 / B6 contract -- only the RENDERED string was "
        "remapped, not the dict key)"
    )

    # And the canonical RISK_BAND_THRESHOLDS dict in canonical_metrics
    # MUST still carry MEDIUM as a key.
    cm_body = (PROJECT_ROOT / "canonical_metrics.py").read_text(encoding="utf-8")
    assert '"MEDIUM"' in cm_body or "'MEDIUM'" in cm_body, (
        "Round 73 / F9: RISK_BAND_THRESHOLDS dict in canonical_metrics "
        "must still carry MEDIUM as a key (canonical band key contract)"
    )


